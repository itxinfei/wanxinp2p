package com.xfjr.consumer.common;


import com.xfjr.common.domain.ErrorCode;

/**
 * 异常编码 0成功、-1熔断、 -2 标准参数校验不通过 -3会话超时
 * 前两位:服务标识
 * 中间两位:模块标识
 * 后两位:异常标识
 * c端用户服务异常编码以14开始
 */
public enum ConsumerErrorCode implements ErrorCode {
	////////////////////////////////////c端用户服务异常编码 //////////////////////////
	/**
	 * 不存在的用户信息
	 */
	E_140101(140101,"不存在的用户信息"),
	E_140102(140102,"请求失败"),
	E_140105(140105,"用户已开户"),
	E_140106(140106,"注册失败"),
	E_140107(140107, "用户已存在"),
	E_140108(140108, "身份信息不一致"),

	E_140131(140131,"用户充值失败"),
	E_140132(140132,"用户存管账户未开通成功"),


	E_140141(140141,"用户提现失败"),


	E_140151(140151,"银行卡已被绑定"),

	////////////////////////////////////会员与积分(FR-127)//////////////////////////
	E_140201(140201,"会员等级配置不存在"),
	E_140202(140202,"会员档案不存在"),
	E_140203(140203,"积分余额不足"),
	E_140204(140204,"积分业务流水号重复"),
	E_140205(140205,"会员/积分参数非法"),

	////////////////////////////////////电子合同与存证(FR-133)//////////////////////////
	E_140301(140301,"合同不存在"),
	E_140302(140302,"合同状态不可签署"),
	E_140303(140303,"合同模板不存在"),
	E_140304(140304,"存证失败"),
	E_140305(140305,"合同参数非法"),

	////////////////////////////////////实名活体/人脸核验(FR-135)//////////////////////////
	E_140401(140401,"活体核验失败"),
	E_140402(140402,"暂无核验记录"),
	E_140405(140405,"实名核验参数非法"),

	////////////////////////////////////管理后台RBAC(FR-131)//////////////////////////
	E_140501(140501,"无权限访问"),
	E_140502(140502,"RBAC 参数/资源非法"),
	;

	private int code;
	private String desc;
		
	public int getCode() {
		return code;
	}

	public String getDesc() {
		return desc;
	}

	private ConsumerErrorCode(int code, String desc) {
		this.code = code;
		this.desc = desc;
	}


	public static ConsumerErrorCode setErrorCode(int code) {
       for (ConsumerErrorCode errorCode : ConsumerErrorCode.values()) {
           if (errorCode.getCode()==code) {
               return errorCode;
           }
       }
	       return null;
	}
}
