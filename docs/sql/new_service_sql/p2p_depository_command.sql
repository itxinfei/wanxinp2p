-- 存管指令与异步通知（FR-134）数据库脚本
-- 为既有 depository_record 表扩展指令审计字段；幂等性：列已存在时跳过（MySQL 8 无 ADD COLUMN IF NOT EXISTS，
-- 请确认列不存在后再执行；重复执行会报 Duplicate column，可安全忽略）

USE `p2p_depository_agent`;

ALTER TABLE `depository_record`
  ADD COLUMN `SERVICE_NAME` varchar(64) DEFAULT NULL COMMENT '存管接口名' AFTER `REQUEST_NO`,
  ADD COLUMN `DIRECTION` varchar(8) DEFAULT NULL COMMENT '指令方向 IN/OUT' AFTER `SERVICE_NAME`,
  ADD COLUMN `AMOUNT` decimal(18,2) DEFAULT NULL COMMENT '指令金额' AFTER `DIRECTION`,
  ADD COLUMN `SERVICE_CODE` varchar(64) DEFAULT NULL COMMENT '业务服务标识(回调区分业务)' AFTER `AMOUNT`,
  ADD COLUMN `STATUS` varchar(16) DEFAULT NULL COMMENT 'INIT/PROCESSING/SUCCESS/FAIL/CANCELED' AFTER `SERVICE_CODE`,
  ADD COLUMN `REQUEST_PAYLOAD` text COMMENT '请求报文(防篡改留痕)' AFTER `RESPONSE_DATA`,
  ADD COLUMN `RETRY_COUNT` int(11) DEFAULT '0' COMMENT '重试次数' AFTER `REQUEST_PAYLOAD`,
  ADD COLUMN `ERROR_MESSAGE` varchar(512) DEFAULT NULL COMMENT '错误信息' AFTER `RETRY_COUNT`,
  ADD COLUMN `UPDATE_DATE` datetime DEFAULT NULL COMMENT '更新时间' AFTER `ERROR_MESSAGE`;

-- 幂等/补偿查询索引
ALTER TABLE `depository_record`
  ADD KEY `idx_request_no` (`REQUEST_NO`);
